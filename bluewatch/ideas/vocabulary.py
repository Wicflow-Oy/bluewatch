"""The words Idea Harbour's rules look for, in English, Finnish and Swedish.

Teams write in the language they think in, so every signal has a word list per language. Finnish and
Swedish build compound words ("mobiilisovellus", "laddstolpe"), so a stem that may end a compound starts
with \\w*. Inflection is covered by \\w* at the end ("maksaa", "maksavat", "maksamme"). Ocean and water
words come from the offline reader's vocabulary (bluewatch/read/keywords.py), so both readers agree on
what counts as ocean.

Every list is plain regular-expression text, matched case-insensitively on whole words.
"""

from __future__ import annotations

import re

from bluewatch.read import keywords


def phrase_pattern(*lists: list[str]) -> re.Pattern[str]:
    """One pattern matching any term of the lists as a whole word."""
    terms = [term for group in lists for term in group]
    return re.compile(r"(?<!\w)(?:" + "|".join(terms) + r")(?!\w)", re.I)


